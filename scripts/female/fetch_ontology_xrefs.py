def get(url):
    for attempt in range(4):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=30) as r:
                return json.loads(r.read())
        except Exception:  # noqa: BLE001 — retry transient network errors
            time.sleep(1.5 * (attempt + 1))
    return None


def uberon_to_fma(uberon):
    curie = uberon.replace('_', ':')
    data = get('https://www.ebi.ac.uk/ols4/api/ontologies/uberon/terms?obo_id=' + urllib.parse.quote(curie))
    terms = (data or {}).get('_embedded', {}).get('terms', [])
    if not terms:
        return None, None
    term = terms[0]
    xrefs = term.get('annotation', {}).get('database_cross_reference', []) or []
    fma = sorted({x for x in xrefs if x.startswith('FMA:')})
    return (fma[0].replace(':', '') if fma else None), term.get('label')


def fma_by_label(label):
    q = urllib.parse.urlencode({'q': label, 'ontology': 'fma', 'queryFields': 'label', 'rows': 25})
    data = get('https://www.ebi.ac.uk/ols4/api/search?' + q)
    for doc in (data or {}).get('response', {}).get('docs', []):
        oid = doc.get('obo_id', '').replace(':', '').upper()
        if doc.get('label', '').lower() == label.lower() and oid.startswith('FMA') and doc.get('ontology_name') == 'fma':
            return oid
    return None


def main():
    _, parts, _ = ml.read_glb(sys.argv[1])
    cache = json.loads(OUT.read_text()) if OUT.exists() else {'uberon': {}, 'labels': {}}
    uberons = sorted({p['extras'].get('ontologyid') for p in parts if str(p['extras'].get('ontologyid', '')).startswith('UBERON')})
    for u in uberons:
        if u in cache['uberon']:
            continue
        fma, label = uberon_to_fma(u)
        cache['uberon'][u] = {'fma': fma, 'label': label}
        print(u, fma, label)
    for label in FMA_LABELS:
        if cache['labels'].get(label) is None:
            cache['labels'][label] = fma_by_label(label)
            print(label, cache['labels'][label])
    cache['source'] = 'EBI OLS4 https://www.ebi.ac.uk/ols4 (UBERON database_cross_reference; FMA exact-label search)'
    cache['retrieved'] = time.strftime('%Y-%m-%d')
    OUT.write_text(json.dumps(cache, indent=1, sort_keys=True))


if __name__ == '__main__':
    main()
